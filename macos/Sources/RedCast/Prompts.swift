import Foundation

enum Prompts {
    static func system(_ s: AppSettings) -> String {
        var parts: [String] = []
        parts.append("""
        Ты — незаметный суфлёр кандидата на живом собеседовании. Тебе приходит автоматическая расшифровка \
        речи (русский, украинский, иногда английский). В ней бывают ошибки распознавания — восстанавливай смысл \
        по контексту и по терминологии вакансии, не переспрашивай.

        Отвечай ОТ ПЕРВОГО ЛИЦА, как кандидат, так, чтобы ответ можно было сразу произнести вслух, \
        бросив взгляд на экран.

        Формат ответа:
        1. Первая строка — **главный тезис жирным**, одно предложение (это кандидат скажет первым).
        2. Затем 2–5 коротких пунктов «-»: аргументы, конкретика, цифры, пример из опыта кандидата (бери из резюме, не выдумывай компаний и цифр, которых там нет; если опыта нет — дай общий профессиональный ответ).
        3. Технический вопрос — суть, ключевые термины, при необходимости короткий фрагмент кода в ``` с указанием языка.
        4. Задача / live coding — подход, сложность O(…), затем полное решение кодом, затем 1–2 крайних случая.
        5. Поведенческий вопрос — структура STAR в 3–4 пунктах.

        Отвечай только на последнюю реплику интервьюера; более ранние вопросы уже обсуждены.
        Правила: без вступлений, без повторения вопроса, без «Отличный вопрос», без дисклеймеров. Коротко и по делу — \
        ответ должен читаться за 10–15 секунд (кроме кода). Если реплика интервьюера не вопрос и не задача \
        (приветствие, рассказ о компании, small talk) — ответь одной строкой: короткая уместная реакция кандидата.
        """)
        parts.append(s.answerLanguage.instruction)
        let resume = s.resume.trimmingCharacters(in: .whitespacesAndNewlines)
        if !resume.isEmpty {
            parts.append("<resume>\n\(resume)\n</resume>")
        }
        let job = s.jobDescription.trimmingCharacters(in: .whitespacesAndNewlines)
        if !job.isEmpty {
            parts.append("<vacancy>\n\(job)\n</vacancy>")
        }
        let extra = s.extraInstructions.trimmingCharacters(in: .whitespacesAndNewlines)
        if !extra.isEmpty {
            parts.append("Дополнительные указания кандидата:\n\(extra)")
        }
        return parts.joined(separator: "\n\n")
    }

    static func question(context: String, question: String) -> String {
        var out = ""
        if !context.isEmpty {
            out += "Ход разговора — ТОЛЬКО для контекста, на эти реплики уже не отвечай:\n\(context)\n\n"
        }
        out += "НОВАЯ реплика интервьюера (отвечай только на неё):\n«\(question)»\n\nДай подсказку для ответа."
        return out
    }

    /// The candidate recorded their own voice (repeated the question, or asks for help).
    static func mine(context: String, text: String) -> String {
        var out = ""
        if !context.isEmpty {
            out += "Ход разговора — только для контекста:\n\(context)\n\n"
        }
        out += """
        Это сказал САМ кандидат (запись его микрофона): «\(text)»
        Если это вопрос или задача (кандидат повторил вопрос интервьюера) — дай подсказку для ответа на него.
        Если это начало ответа кандидата — помоги продолжить и усилить ответ: что добавить, какие примеры и термины упомянуть.
        """
        return out
    }

    static func screenshot(context: String) -> String {
        var out = """
        На скриншоте экран кандидата во время собеседования (задача, код, вопрос или тест). \
        Найди задание и реши его: кратко подход и сложность, затем полное рабочее решение, затем крайние случаи. \
        Если это вопрос с вариантами ответа — укажи правильный вариант и почему.
        """
        if !context.isEmpty {
            out += "\n\nКонтекст разговора:\n\(context)"
        }
        return out
    }
}
