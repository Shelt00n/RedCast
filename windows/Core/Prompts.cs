using System;
using System.Collections.Generic;

namespace RedCast.Core;

public static class Prompts
{
    const string Base = @"Ты — незаметный суфлёр кандидата на живом собеседовании. Тебе приходит автоматическая расшифровка речи (русский, украинский, иногда английский). В ней бывают ошибки распознавания — восстанавливай смысл по контексту и по терминологии вакансии, не переспрашивай.

Отвечай ОТ ПЕРВОГО ЛИЦА, как кандидат, так, чтобы ответ можно было сразу произнести вслух, бросив взгляд на экран.

Формат ответа:
1. Первая строка — **главный тезис жирным**, одно предложение (это кандидат скажет первым).
2. Затем 2–5 коротких пунктов «-»: аргументы, конкретика, цифры, пример из опыта кандидата (бери из резюме, не выдумывай компаний и цифр, которых там нет; если опыта нет — дай общий профессиональный ответ).
3. Технический вопрос — суть, ключевые термины, при необходимости короткий фрагмент кода в ``` с указанием языка.
4. Задача / live coding — подход, сложность O(…), затем полное решение кодом, затем 1–2 крайних случая.
5. Поведенческий вопрос — структура STAR в 3–4 пунктах.

Отвечай только на последнюю реплику интервьюера; более ранние вопросы уже обсуждены.
Правила: без вступлений, без повторения вопроса, без «Отличный вопрос», без дисклеймеров. Коротко и по делу — ответ должен читаться за 10–15 секунд (кроме кода). Если реплика интервьюера не вопрос и не задача (приветствие, рассказ о компании, small talk) — ответь одной строкой: короткая уместная реакция кандидата.";

    public static string System(AppSettings s)
    {
        var parts = new List<string> { Base, s.AnswerLanguageInstruction };
        if (!string.IsNullOrWhiteSpace(s.Resume)) parts.Add("<resume>\n" + s.Resume.Trim() + "\n</resume>");
        if (!string.IsNullOrWhiteSpace(s.JobDescription)) parts.Add("<vacancy>\n" + s.JobDescription.Trim() + "\n</vacancy>");
        if (!string.IsNullOrWhiteSpace(s.ExtraInstructions)) parts.Add("Дополнительные указания кандидата:\n" + s.ExtraInstructions.Trim());
        return string.Join("\n\n", parts);
    }

    public static string Question(string context, string question)
    {
        var o = "";
        if (context.Length > 0) o += "Ход разговора — ТОЛЬКО для контекста, на эти реплики уже не отвечай:\n" + context + "\n\n";
        return o + "НОВАЯ реплика интервьюера (отвечай только на неё):\n«" + question + "»\n\nДай подсказку для ответа.";
    }

    public static string Mine(string context, string text)
    {
        var o = "";
        if (context.Length > 0) o += "Ход разговора — только для контекста:\n" + context + "\n\n";
        return o + "Это сказал САМ кандидат (запись его микрофона): «" + text + "»\n" +
               "Если это вопрос или задача (кандидат повторил вопрос интервьюера) — дай подсказку для ответа на него.\n" +
               "Если это начало ответа кандидата — помоги продолжить и усилить ответ: что добавить, какие примеры и термины упомянуть.";
    }

    public static string Screenshot(string context)
    {
        var o = "На скриншоте экран кандидата во время собеседования (задача, код, вопрос или тест). " +
                "Найди задание и реши его: кратко подход и сложность, затем полное рабочее решение, затем крайние случаи. " +
                "Если это вопрос с вариантами ответа — укажи правильный вариант и почему.";
        if (context.Length > 0) o += "\n\nКонтекст разговора:\n" + context;
        return o;
    }
}
